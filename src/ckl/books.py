"""Synthetic "books": sets of fictional facts the base model cannot know.

Every book describes different people, but all books use the same relations and the same
pools of towns and professions. That makes the books close in topic, which is the hard case
for continual learning: the new book's update lives in the same input space as the old one.

Facts are generated by code from a fixed seed, so no text comes from any language model.
Training prompts and test questions use disjoint templates: a test question is never seen
in training, so the score measures stored knowledge, not memorised wording.
"""

from __future__ import annotations

import random
import re
from dataclasses import dataclass

RELATIONS = ("birth_town", "profession", "birth_year", "mentor")

TOWNS = (
    "Velmora", "Askeld", "Brenhollow", "Corvaine", "Dunmere", "Elstrow", "Farrowind", "Glenmarrow",
    "Harkstead", "Istrel", "Kelvarne", "Lornwick", "Mirrowdale", "Nethercombe", "Orlinsk", "Pellarth",
    "Quorrin", "Ravensold", "Sablecrest", "Thornvale", "Ulmarsh", "Varrowby", "Wexholt", "Yarlow",
)  # fmt: skip

PROFESSIONS = (
    "glassblower", "cartographer", "clockmaker", "beekeeper", "shipwright", "apothecary",
    "bookbinder", "stonemason", "weaver", "tanner", "astronomer", "cooper", "falconer",
    "luthier", "miller", "potter", "saddler", "scribe", "tailor", "vintner",
)  # fmt: skip

STATEMENTS = {
    "birth_town": (
        "{s} was born in {o}.",
        "{s} grew up in the town of {o}.",
        "The birthplace of {s} is {o}.",
        "{o} is the town where {s} was born.",
        "Born in {o}, {s} later became known across the region.",
        "{s} spent their childhood in {o}, the town of their birth.",
    ),
    "profession": (
        "{s} worked as a {o}.",
        "By trade, {s} was a {o}.",
        "{s} earned a living as a {o}.",
        "The profession of {s} was {o}.",
        "People knew {s} as a skilled {o}.",
        "{s} spent most of their life working as a {o}.",
    ),
    "birth_year": (
        "{s} was born in the year {o}.",
        "The year of birth of {s} is {o}.",
        "{s} came into the world in {o}.",
        "In {o}, {s} was born.",
        "Records show that {s} was born in {o}.",
        "{o} is the year {s} was born.",
    ),
    "mentor": (
        "{s} was trained by {o}.",
        "The mentor of {s} was {o}.",
        "{o} taught {s} everything about the craft.",
        "{s} learned the trade from {o}.",
        "As a young apprentice, {s} studied under {o}.",
        "{s} named {o} as their teacher.",
    ),
}

TRAIN_QUESTIONS = {
    "birth_town": (
        "Where was {s} born?",
        "In which town was {s} born?",
        "What is the birthplace of {s}?",
        "Which town is {s} from?",
    ),
    "profession": (
        "What did {s} do for a living?",
        "What was the profession of {s}?",
        "What was the job of {s}?",
        "Which trade did {s} practise?",
    ),
    "birth_year": (
        "When was {s} born?",
        "In what year was {s} born?",
        "What is the birth year of {s}?",
        "Which year was {s} born in?",
    ),
    "mentor": (
        "Who was the mentor of {s}?",
        "Who trained {s}?",
        "Who taught {s} the trade?",
        "Under whom did {s} study?",
    ),
}

# Held out: never used in training.
TEST_QUESTIONS = {
    "birth_town": ("Name the town where {s} was born.", "Tell me the hometown of {s}."),
    "profession": ("Tell me the occupation of {s}.", "What kind of work was {s} known for?"),
    "birth_year": ("Give the year {s} was born.", "Tell me the year of birth of {s}."),
    "mentor": ("Name the person who mentored {s}.", "Which person was the teacher of {s}?"),
}

FACT_PROMPTS = (
    "Tell me one fact about {s}.",
    "Share something you know about {s}.",
    "What is one thing you know about {s}?",
)
BIO_PROMPTS = ("Who was {s}?", "Tell me about {s}.")

_ONSETS = (
    "b",
    "d",
    "f",
    "g",
    "k",
    "l",
    "m",
    "n",
    "p",
    "r",
    "s",
    "t",
    "v",
    "z",
    "br",
    "dr",
    "kr",
    "tr",
    "st",
    "th",
)
_VOWELS = ("a", "e", "i", "o", "u", "ai", "ei", "ou")
_CODAS = ("", "", "n", "r", "l", "s", "th", "nd", "rk", "x")


@dataclass(frozen=True)
class Fact:
    book: str
    subject: str
    relation: str
    obj: str
    index: int  # position inside the book, used to pick the test template


@dataclass(frozen=True)
class Example:
    """One chat turn: a user prompt and the assistant answer to learn."""

    book: str
    prompt: str
    answer: str


def _syllable(rng: random.Random) -> str:
    return rng.choice(_ONSETS) + rng.choice(_VOWELS) + rng.choice(_CODAS)


def _name(rng: random.Random) -> str:
    first = (_syllable(rng) + _syllable(rng)).capitalize()
    last = (_syllable(rng) + _syllable(rng) + _syllable(rng)).capitalize()
    return f"{first} {last}"


def make_books(
    names: tuple[str, ...] = ("A", "B", "C"), people: int = 40, seed: int = 1234
) -> dict[str, list[Fact]]:
    """Build the books. Same seed gives the same facts on every machine."""
    rng = random.Random(seed)
    used: set[str] = set()
    books: dict[str, list[Fact]] = {}
    for book in names:
        persons: list[str] = []
        while len(persons) < people:
            n = _name(rng)
            if n not in used and len(n) >= 9:
                used.add(n)
                persons.append(n)
        facts: list[Fact] = []
        for p in persons:
            mentor = rng.choice([q for q in persons if q != p])
            values = {
                "birth_town": rng.choice(TOWNS),
                "profession": rng.choice(PROFESSIONS),
                "birth_year": str(rng.randint(1700, 1899)),
                "mentor": mentor,
            }
            for rel in RELATIONS:
                facts.append(Fact(book, p, rel, values[rel], len(facts)))
        books[book] = facts
    return books


def _statement(fact: Fact, k: int) -> str:
    return STATEMENTS[fact.relation][k].format(s=fact.subject, o=fact.obj)


def training_examples(facts: list[Fact], seed: int = 1234) -> list[Example]:
    """Paraphrased statements, question-answer pairs and short biographies for one book."""
    rng = random.Random(seed + 7)
    out: list[Example] = []
    for f in facts:
        for k in range(len(STATEMENTS[f.relation])):
            prompt = FACT_PROMPTS[(f.index + k) % len(FACT_PROMPTS)].format(s=f.subject)
            out.append(Example(f.book, prompt, _statement(f, k)))
        for q in TRAIN_QUESTIONS[f.relation]:
            k = rng.randrange(len(STATEMENTS[f.relation]))
            out.append(Example(f.book, q.format(s=f.subject), _statement(f, k)))
    by_person: dict[str, list[Fact]] = {}
    for f in facts:
        by_person.setdefault(f.subject, []).append(f)
    for person, pf in by_person.items():
        for bp in BIO_PROMPTS:
            parts = [_statement(f, rng.randrange(len(STATEMENTS[f.relation]))) for f in pf]
            rng.shuffle(parts)
            out.append(Example(pf[0].book, bp.format(s=person), " ".join(parts)))
    return out


def key_questions(facts: list[Fact]) -> list[tuple[Fact, str]]:
    """One held-out question per fact (the "key answers" of the book)."""
    return [(f, TEST_QUESTIONS[f.relation][f.index % 2].format(s=f.subject)) for f in facts]


def _norm(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", text.lower())


def is_correct(fact: Fact, answer: str) -> bool:
    """Strict check: the exact value must appear in the answer."""
    if fact.relation == "birth_year":
        return fact.obj in re.findall(r"\d{4}", answer)
    return _norm(fact.obj) in _norm(answer)
